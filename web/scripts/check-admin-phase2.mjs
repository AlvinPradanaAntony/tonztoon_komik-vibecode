const require = createRequire(import.meta.url), cache = new Map();
function load(name) {
  const file = path.resolve('src', name.replace(/^@\//, '') + '.ts');
  if (cache.has(file)) return cache.get(file);
  const exports = {}; cache.set(file, exports);
  const compiled = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } });
  new Function('require', 'exports', compiled.outputText)(id => id.startsWith('@/') ? load(id) : id.startsWith('.') ? load(path.relative('src', path.resolve(path.dirname(file), id)).replaceAll('\\', '/')) : require(id), exports);
  return exports;
}
